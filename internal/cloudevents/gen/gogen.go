package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"text/template"
)

// initialisms we upper-case wholesale when Go-ifying snake_case field names.
var initialisms = map[string]string{
	"id":   "ID",
	"url":  "URL",
	"uri":  "URI",
	"ip":   "IP",
	"http": "HTTP",
	"api":  "API",
	"json": "JSON",
}

// goName converts a dotted/snake-cased catalog identifier to a CamelCase Go
// identifier. It splits on '.' and '_', title-cases each segment, and
// upper-cases known initialisms.
func goName(s string) string {
	// split on both '.' and '_'
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '.' || r == '_' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		lower := strings.ToLower(p)
		if up, ok := initialisms[lower]; ok {
			b.WriteString(up)
			continue
		}
		// Preserve trailing digits (e.g. v1 → V1) by title-casing the first rune.
		runes := []rune(lower)
		runes[0] = []rune(strings.ToUpper(string(runes[0])))[0]
		b.WriteString(string(runes))
	}
	return b.String()
}

// eventGoName strips the "run.yipyap." prefix and Go-ifies the rest.
func eventGoName(eventType string) string {
	trimmed := strings.TrimPrefix(eventType, "run.yipyap.")
	return goName(trimmed)
}

// goType maps a catalog Field to its Go type representation.
func goType(f Field) string {
	switch f.Type {
	case "string":
		if f.Format == "rfc3339" {
			return "time.Time"
		}
		return "string"
	case "int":
		return "int64"
	case "bool":
		return "bool"
	case "object":
		return "map[string]any"
	case "array":
		if f.Items == nil {
			return "[]any"
		}
		return "[]" + goType(*f.Items)
	default:
		// Fall back to `any` for unknown types; the parser should catch most
		// issues, but the generator shouldn't panic.
		return "any"
	}
}

// jsonTag returns the `json:"..."` struct tag content (without surrounding backticks).
func jsonTag(f Field) string {
	if f.Required {
		return fmt.Sprintf(`json:"%s"`, f.Name)
	}
	return fmt.Sprintf(`json:"%s,omitempty"`, f.Name)
}

type tmplField struct {
	GoName  string
	GoType  string
	JSONTag string
}

type tmplEvent struct {
	GoName string
	Type   string
	Fields []tmplField
}

type tmplData struct {
	Package string
	Events  []tmplEvent
}

const goTypesTmpl = `// Code generated by internal/cloudevents/gen. DO NOT EDIT.

package {{ .Package }}

import (
	"time"
)

var _ = time.Time{}

{{ range .Events }}
const Type{{ .GoName }} = "{{ .Type }}"

type {{ .GoName }}Data struct {
{{- range .Fields }}
	{{ .GoName }} {{ .GoType }} ` + "`{{ .JSONTag }}`" + `
{{- end }}
}
{{ end }}
`

// RenderGoTypes renders the catalog as a self-contained Go source file declaring
// one Type* constant and one *Data struct per event. The output is gofmt-clean
// (run through go/format.Source) and is safe to write to disk via go:generate.
func RenderGoTypes(cat *Catalog, pkg string) ([]byte, error) {
	data := tmplData{Package: pkg}
	for _, ev := range cat.Events {
		te := tmplEvent{
			GoName: eventGoName(ev.Type),
			Type:   ev.Type,
		}
		for _, f := range ev.Data {
			te.Fields = append(te.Fields, tmplField{
				GoName:  goName(f.Name),
				GoType:  goType(f),
				JSONTag: jsonTag(f),
			})
		}
		data.Events = append(data.Events, te)
	}

	t, err := template.New("gotypes").Parse(goTypesTmpl)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w\n--- raw ---\n%s", err, buf.String())
	}
	return formatted, nil
}

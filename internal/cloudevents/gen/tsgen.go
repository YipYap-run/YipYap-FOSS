package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// tsType maps a catalog Field to its TypeScript type representation.
//
// Note: catalog string formats (rfc3339, ulid, uri) stay as `string` in
// TypeScript, format-level validation lives in the JSON Schemas, not the
// generated types. String fields with an `enum` render as a union of quoted
// literals in catalog order.
func tsType(f Field) string {
	switch f.Type {
	case "string":
		if len(f.Enum) > 0 {
			parts := make([]string, 0, len(f.Enum))
			for _, e := range f.Enum {
				// Use encoding/json to produce a properly-quoted string literal.
				// JSON and TypeScript string literal syntax are compatible for
				// the character set we expect in enums.
				b, err := json.Marshal(e)
				if err != nil {
					// Fallback: raw quote. Should never happen for Go strings.
					parts = append(parts, fmt.Sprintf("%q", e))
					continue
				}
				parts = append(parts, string(b))
			}
			return strings.Join(parts, " | ")
		}
		return "string"
	case "int":
		return "number"
	case "bool":
		return "boolean"
	case "object":
		return "Record<string, unknown>"
	case "array":
		if f.Items == nil {
			return "unknown[]"
		}
		return tsType(*f.Items) + "[]"
	default:
		return "unknown"
	}
}

// RenderTSTypes renders the catalog as a single TypeScript source file
// declaring one `Type*` constant and one `*Data` interface per event. The
// function is pure and deterministic: it iterates the catalog in the order
// the parser provides (sorted by Type) and uses no map iteration.
//
// Field names in interfaces stay in the catalog's snake_case to match the
// over-the-wire JSON. Constants and interface names use the same CamelCase
// transform as the Go generator (see goName / eventGoName in gogen.go).
func RenderTSTypes(cat *Catalog) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/cloudevents/gen. DO NOT EDIT.\n")

	for _, ev := range cat.Events {
		// Defensive: reject duplicate field names in the same event. The YAML
		// parser won't produce these, but a manually-constructed Catalog could.
		seen := make(map[string]struct{}, len(ev.Data))
		for _, f := range ev.Data {
			if _, dup := seen[f.Name]; dup {
				return nil, fmt.Errorf("event %s: duplicate field name %q", ev.Type, f.Name)
			}
			seen[f.Name] = struct{}{}
		}

		name := eventGoName(ev.Type)
		buf.WriteByte('\n')
		fmt.Fprintf(&buf, "export const Type%s = %q;\n", name, ev.Type)
		buf.WriteByte('\n')
		fmt.Fprintf(&buf, "export interface %sData {\n", name)
		for _, f := range ev.Data {
			opt := ""
			if !f.Required {
				opt = "?"
			}
			fmt.Fprintf(&buf, "  %s%s: %s;\n", f.Name, opt, tsType(f))
		}
		buf.WriteString("}\n")
	}

	return buf.Bytes(), nil
}
